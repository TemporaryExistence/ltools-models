-- Load the FAA Wildlife Strike Database public Excel export (Public.xlsx, built 2026-10-06) into MotherDuck.
-- Step 1 (local, once): duckdb -c "COPY (SELECT * FROM read_xlsx('Public.xlsx', all_varchar=true)) TO 'public_allvarchar.parquet'"
-- Step 2: run this from units/ltools/public-data/faa_wildlife/raw against md:ltools.
-- NOT loaded on purpose: REMARKS, COMMENTS, OTHER_SPECIFY, EFFECT_OTHER (free text that could hold incidental names),
-- REPORTED_NAME, REPORTED_TITLE (reporter identity; "REDACTED" at source), BIRD_BAND_NUMBER, IMAGE, TRANSFER.
CREATE SCHEMA IF NOT EXISTS ltools.faa_wildlife;
CREATE OR REPLACE TABLE ltools.faa_wildlife.strikes AS
WITH r AS (
  SELECT * EXCLUDE (REMARKS, COMMENTS, OTHER_SPECIFY, EFFECT_OTHER, REPORTED_NAME, REPORTED_TITLE, BIRD_BAND_NUMBER, IMAGE, TRANSFER)
  FROM read_parquet('public_allvarchar.parquet')
)
SELECT
  INDEX_NR::BIGINT AS strike_id,
  INCIDENT_DATE::DATE AS incident_date,
  INCIDENT_YEAR::INTEGER AS incident_year,
  INCIDENT_MONTH::INTEGER AS incident_month,
  nullif(trim(TIME), '') AS incident_time,
  nullif(trim(TIME_OF_DAY), '') AS time_of_day,
  nullif(trim(AIRPORT_ID), '') AS airport_id,
  nullif(trim(AIRPORT), '') AS airport,
  TRY_CAST(nullif(trim(LATITUDE), '') AS DOUBLE) AS airport_latitude,
  TRY_CAST(nullif(trim(LONGITUDE), '') AS DOUBLE) AS airport_longitude,
  nullif(trim(RUNWAY), '') AS runway,
  nullif(trim(STATE), '') AS state,
  nullif(trim(FAAREGION), '') AS faa_region,
  nullif(trim(LOCATION), '') AS location,
  nullif(trim(OPID), '') AS operator_id,
  nullif(trim(OPERATOR), '') AS operator,
  nullif(trim(REG), '') AS aircraft_registration,
  nullif(trim(FLT), '') AS flight_number,
  nullif(trim(AIRCRAFT), '') AS aircraft,
  nullif(trim(AMA), '') AS aircraft_make_code,
  nullif(trim(AMO), '') AS aircraft_model_code,
  nullif(trim(EMA), '') AS engine_make_code,
  nullif(trim(EMO), '') AS engine_model_code,
  nullif(trim(AC_CLASS), '') AS aircraft_class_code,
  TRY_CAST(nullif(trim(AC_MASS), '') AS INTEGER) AS aircraft_mass_code,
  nullif(trim(TYPE_ENG), '') AS engine_type_code,
  TRY_CAST(nullif(trim(NUM_ENGS), '') AS INTEGER) AS num_engines,
  nullif(trim(PHASE_OF_FLIGHT), '') AS phase_of_flight,
  TRY_CAST(nullif(trim(HEIGHT), '') AS DOUBLE) AS height_ft,
  TRY_CAST(nullif(trim(SPEED), '') AS DOUBLE) AS speed_kts,
  TRY_CAST(nullif(trim(DISTANCE), '') AS DOUBLE) AS distance_nm,
  nullif(trim(SKY), '') AS sky,
  nullif(trim(PRECIPITATION), '') AS precipitation,
  TRY_CAST(nullif(trim(AOS), '') AS DOUBLE) AS hours_out_of_service,
  TRY_CAST(nullif(replace(trim(COST_REPAIRS), ',', ''), '') AS DOUBLE) AS cost_repairs,
  TRY_CAST(nullif(replace(trim(COST_OTHER), ',', ''), '') AS DOUBLE) AS cost_other,
  TRY_CAST(nullif(replace(trim(COST_REPAIRS_INFL_ADJ), ',', ''), '') AS DOUBLE) AS cost_repairs_infl_adj,
  TRY_CAST(nullif(replace(trim(COST_OTHER_INFL_ADJ), ',', ''), '') AS DOUBLE) AS cost_other_infl_adj,
  INGESTED_OTHER = '1' AS ingested_other,
  INDICATED_DAMAGE = '1' AS indicated_damage,
  nullif(trim(DAMAGE_LEVEL), '') AS damage_level_code,
  STR_RAD = '1' AS struck_radome, DAM_RAD = '1' AS damaged_radome,
  STR_WINDSHLD = '1' AS struck_windshield, DAM_WINDSHLD = '1' AS damaged_windshield,
  STR_NOSE = '1' AS struck_nose, DAM_NOSE = '1' AS damaged_nose,
  STR_ENG1 = '1' AS struck_engine1, DAM_ENG1 = '1' AS damaged_engine1, ING_ENG1 = '1' AS ingested_engine1,
  STR_ENG2 = '1' AS struck_engine2, DAM_ENG2 = '1' AS damaged_engine2, ING_ENG2 = '1' AS ingested_engine2,
  STR_ENG3 = '1' AS struck_engine3, DAM_ENG3 = '1' AS damaged_engine3, ING_ENG3 = '1' AS ingested_engine3,
  STR_ENG4 = '1' AS struck_engine4, DAM_ENG4 = '1' AS damaged_engine4, ING_ENG4 = '1' AS ingested_engine4,
  STR_PROP = '1' AS struck_propeller, DAM_PROP = '1' AS damaged_propeller,
  STR_WING_ROT = '1' AS struck_wing_rotor, DAM_WING_ROT = '1' AS damaged_wing_rotor,
  STR_FUSE = '1' AS struck_fuselage, DAM_FUSE = '1' AS damaged_fuselage,
  STR_LG = '1' AS struck_landing_gear, DAM_LG = '1' AS damaged_landing_gear,
  STR_TAIL = '1' AS struck_tail, DAM_TAIL = '1' AS damaged_tail,
  STR_LGHTS = '1' AS struck_lights, DAM_LGHTS = '1' AS damaged_lights,
  STR_OTHER = '1' AS struck_other, DAM_OTHER = '1' AS damaged_other,
  nullif(trim(EFFECT), '') AS effect,
  nullif(trim(SPECIES_ID), '') AS species_id,
  nullif(trim(SPECIES), '') AS species,
  OUT_OF_RANGE_SPECIES = '1' AS out_of_range_species,
  REMAINS_COLLECTED = '1' AS remains_collected,
  REMAINS_SENT = '1' AS remains_sent_to_smithsonian,
  nullif(trim(WARNED), '') AS pilot_warned,
  nullif(trim(NUM_SEEN), '') AS num_seen,
  nullif(trim(NUM_STRUCK), '') AS num_struck,
  nullif(trim(SIZE), '') AS wildlife_size,
  nullif(trim(ENROUTE_STATE), '') AS enroute_state,
  TRY_CAST(nullif(trim(NR_INJURIES), '') AS INTEGER) AS injuries,
  TRY_CAST(nullif(trim(NR_FATALITIES), '') AS INTEGER) AS fatalities,
  nullif(trim(SOURCE), '') AS report_source,
  nullif(trim(PERSON), '') AS reporter_role,
  TRY_CAST(nullif(trim(LUPDATE), '') AS DATE) AS last_updated
FROM r;
SELECT count(*) AS strikes, min(incident_date), max(incident_date), count(cost_repairs), sum(injuries), sum(fatalities) FROM ltools.faa_wildlife.strikes;
